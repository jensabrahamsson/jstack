def render_status(graph):
    lines = ["| Task | Traces to | Blocked by | Scope | Status | Branch / SHA | Evidence |",
             "|---|---|---|---|---|---|---|"]
    for task in graph["tasks"]:
        evidence = []
        if task.get("review"):
            evidence.append("review %s @ %s" % (task["review"].get("verdict"), task["review"].get("sha")))
        for ver in task.get("verifications") or []:
            evidence.append("%s %s @ %s [%s]" % (ver.get("command"), ver.get("result"),
                                                 ver.get("revision"),
                                                 ",".join(ver.get("criteria") or [])))
        if task.get("landed"):
            evidence.append("landed %s -> %s" % (task["landed"].get("tip_sha"),
                                                 task["landed"].get("landing_sha")))
        lines.append("| %s %s | %s | %s | %s | %s | %s | %s |" % (
            task["id"], task.get("title", ""),
            ", ".join(task.get("traces_to") or []) or "-",
            ", ".join(task.get("blocked_by") or []) or "-",
            ", ".join("`%s`" % s for s in task.get("scope") or []) or "-",
            task.get("status"),
            ("%s @ %s" % (task["branch"], task["tip_sha"])) if task.get("branch") else "-",
            "; ".join(evidence) or "-"))
    ready = ready_tasks(graph)
    lines.append("")
    lines.append("Ready (frontier): %s" % (", ".join(ready) if ready else "none"))
    return "\n".join(lines)


