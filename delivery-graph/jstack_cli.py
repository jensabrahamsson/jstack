#!/usr/bin/env python3
"""Machine-checkable delivery graph for the delivery-graph skill.

Reads one fenced ```jstack-graph JSON block embedded in the project's
plan file (PLAN.md or the file that owns the plan), validates the graph,
computes ready tasks, guards status transitions against git and against
structured verification evidence, and renders the human status view from
the same data. The JSON block is the single source of truth; the rendered
view between the jstack:status markers is generated, never hand-edited.

Python 3.10+ standard library only. No network, no writes except
`transition`, the `record-*` / `set-tip` commands and
`render --write` / `status --write`. Every write replaces the plan
atomically (temp file in the same directory + `os.replace`, so a crash
mid-write leaves the old file intact) and is serialized across
processes with an advisory lock (`fcntl.flock` on the sibling
`<plan>.jstack.lock` file). On platforms without `fcntl` (Windows)
the write is still atomic but falls back to no lock.

Graph shape (all task fields except id/status optional but validated):

    {
      "version": 1,
      "integration_branch": "int/<goal>",
      "delivery_branch": "main",
      "candidate_sha": "<full sha>",
      "questions": [{"id": "Q1", "answered": true}],
      "tasks": [{
        "id": "T1", "title": "...", "traces_to": ["R1"],
        "acceptance_criteria": ["AC1"],
        "blocked_by": ["T2", "Q1"], "scope": ["src/export/"],
        "status": "blocked",
        "branch": "feat/x", "base_sha": "...", "tip_sha": "...",
        "worktree": "../wt-t1",
        "review": {"sha": "...", "verdict": "pass", "reviewer": "x"},
        "verifications": [{"command": "pytest -q", "result": "pass",
          "revision": "<sha>", "environment": "local py3.12",
          "criteria": ["AC1"]}],
        "repair": {"max_attempts": 3, "max_seconds": 3600,
          "attempts": [{"n": 1, "failure_signature": "KeyError: x",
            "diagnosis": "...", "result": "fail"}]},
        "landed": {"tip_sha": "...", "landing_sha": "..."}
      }]
    }

Task loop vs delivery graph: the graph (this file) is acyclic. The loop
inside a task (build -> test -> review -> repair) is bounded by
repair.max_attempts; a joint-verification failure does not reopen tasks,
it creates a new correction task with its own evidence.
"""

import argparse
import contextlib
import datetime
import fnmatch
import json
import os
import re
import subprocess
import sys
import tempfile

try:
    import fcntl
except ImportError:  # Windows: atomic writes still apply, no lock.
    fcntl = None

STATUSES = ("blocked", "ready", "in_progress", "review", "repairing",
            "integrated", "verified", "done", "stopped")
SATISFYING = ("integrated", "verified", "done")

ALLOWED = {
    "blocked": {"ready", "stopped"},
    "ready": {"in_progress", "blocked", "stopped"},
    "in_progress": {"review", "repairing", "blocked", "stopped"},
    "review": {"integrated", "repairing", "in_progress", "stopped"},
    "repairing": {"in_progress", "blocked", "stopped"},
    "integrated": {"verified", "stopped"},
    "verified": {"done", "stopped"},
    "stopped": {"blocked", "ready"},
    "done": set(),
}

BLOCK_RE = re.compile(r"```jstack-graph[ \t]*\n(.*?)```", re.DOTALL)
VIEW_START = "<!-- jstack:status:start (generated by jstack; do not edit) -->"
VIEW_END = "<!-- jstack:status:end -->"


# --------------------------------------------------------------------------
# Plan file: load / save the embedded graph
# --------------------------------------------------------------------------

class PlanError(Exception):
    pass


def load_plan(path):
    try:
        with open(path, encoding="utf-8") as handle:
            text = handle.read()
    except OSError as exc:
        raise PlanError("cannot read plan %s: %s" % (path, exc))
    match = BLOCK_RE.search(text)
    if not match:
        raise PlanError("no ```jstack-graph block found in %s" % path)
    try:
        graph = json.loads(match.group(1))
    except ValueError as exc:
        raise PlanError("jstack-graph block is not valid JSON: %s" % exc)
    if not isinstance(graph, dict) or not isinstance(graph.get("tasks"), list):
        raise PlanError("jstack-graph block must be an object with a tasks list")
    return text, graph


SHA_RE = re.compile(r"^[0-9a-fA-F]{40}$")

_held_locks = set()


def lock_path_for(plan_path):
    return "%s.jstack.lock" % plan_path


@contextlib.contextmanager
def plan_lock(plan_path):
    """Advisory cross-process lock on `<plan>.jstack.lock` (POSIX).

    Re-entrant within one process for the same plan. On platforms
    without `fcntl` (Windows) this is a no-op: writes remain atomic
    via `save_plan`, but concurrent writers are not serialized.
    """
    if fcntl is None:
        yield
        return
    key = os.path.abspath(plan_path)
    if key in _held_locks:
        yield
        return
    handle = open(lock_path_for(plan_path), "a+", encoding="utf-8")
    try:
        fcntl.flock(handle, fcntl.LOCK_EX)
        _held_locks.add(key)
        try:
            yield
        finally:
            _held_locks.discard(key)
            fcntl.flock(handle, fcntl.LOCK_UN)
    finally:
        handle.close()


def save_plan(path, text, graph):
    block = "```jstack-graph\n%s\n```" % json.dumps(graph, indent=2)
    new_text, count = BLOCK_RE.subn(lambda _m: block, text, count=1)
    if count != 1:
        raise PlanError("could not rewrite jstack-graph block in %s" % path)
    if VIEW_START in new_text and VIEW_END in new_text:
        view = "%s\n%s\n%s" % (VIEW_START, render_status(graph), VIEW_END)
        new_text = re.sub(re.escape(VIEW_START) + r".*?" + re.escape(VIEW_END),
                          lambda _m: view, new_text, flags=re.DOTALL)
    directory = os.path.dirname(os.path.abspath(path)) or "."
    fd, tmp = tempfile.mkstemp(dir=directory, prefix=".jstack-", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(new_text)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise
    return new_text


def tasks_by_id(graph):
    return {t.get("id"): t for t in graph["tasks"] if isinstance(t, dict)}


def questions_by_id(graph):
    out = {}
    for q in graph.get("questions") or []:
        if isinstance(q, dict) and q.get("id"):
            out[q["id"]] = q
    return out


# --------------------------------------------------------------------------
# Validation (step 1 of the recommended order)
# --------------------------------------------------------------------------

def find_cycle(graph):
    by_id = tasks_by_id(graph)
    state, stack = {}, []

    def visit(tid):
        state[tid] = 1
        stack.append(tid)
        for dep in by_id[tid].get("blocked_by") or []:
            if dep not in by_id:
                continue
            if state.get(dep) == 1:
                return stack[stack.index(dep):] + [dep]
            if state.get(dep, 0) == 0:
                found = visit(dep)
                if found:
                    return found
        stack.pop()
        state[tid] = 2
        return None

    for tid in by_id:
        if state.get(tid, 0) == 0:
            found = visit(tid)
            if found:
                return found
    return None


def validate(graph):
    """Return a list of error strings; empty means the graph is valid."""
    errors = []
    by_id, seen = {}, set()
    for task in graph["tasks"]:
        if not isinstance(task, dict) or not task.get("id"):
            errors.append("task without an id: %r" % (task,))
            continue
        if task["id"] in seen:
            errors.append("duplicate task id: %s" % task["id"])
        seen.add(task["id"])
        by_id[task["id"]] = task
    questions = questions_by_id(graph)
    for task in graph["tasks"]:
        if not isinstance(task, dict) or not task.get("id"):
            continue
        tid = task["id"]
        if task.get("status") not in STATUSES:
            errors.append("%s: unknown status %r (want one of %s)"
                          % (tid, task.get("status"), ", ".join(STATUSES)))
        if not task.get("scope"):
            errors.append("%s: missing work area (scope is empty)" % tid)
        if not task.get("traces_to"):
            errors.append("%s: traces_to is empty (scope creep, delivery-graph SS1)" % tid)
        if not task.get("acceptance_criteria"):
            errors.append("%s: no acceptance_criteria named" % tid)
        for dep in task.get("blocked_by") or []:
            if dep not in by_id and dep not in questions:
                errors.append("%s: blocked_by unknown task/question %s" % (tid, dep))
        review = task.get("review")
        if review is not None:
            if not isinstance(review, dict) or not review.get("sha"):
                errors.append("%s: review record needs a sha" % tid)
            elif review.get("verdict") not in ("pass", "fail", None):
                errors.append("%s: review verdict must be pass or fail" % tid)
        for i, ver in enumerate(task.get("verifications") or []):
            for field in ("command", "result", "revision", "environment", "criteria"):
                if not ver.get(field):
                    errors.append("%s: verifications[%d] missing %s" % (tid, i, field))
            if ver.get("result") not in ("pass", "fail", None):
                errors.append("%s: verifications[%d] result must be pass or fail" % (tid, i))
        repair = task.get("repair") or {}
        if repair:
            if not isinstance(repair.get("max_attempts"), int) or repair["max_attempts"] < 1:
                errors.append("%s: repair.max_attempts must be a positive integer" % tid)
            if repair.get("max_seconds") is not None and (
                    not isinstance(repair.get("max_seconds"), (int, float))
                    or isinstance(repair.get("max_seconds"), bool)
                    or repair["max_seconds"] < 0):
                errors.append("%s: repair.max_seconds must be a non-negative number" % tid)
            for i, att in enumerate(repair.get("attempts") or []):
                if not att.get("failure_signature"):
                    errors.append("%s: repair.attempts[%d] missing failure_signature" % (tid, i))
                for field in ("started_at", "ended_at"):
                    if att.get(field) and _parse_iso(att[field]) is None:
                        errors.append("%s: repair.attempts[%d] %s is not an ISO timestamp"
                                      % (tid, i, field))
    cycle = find_cycle(graph)
    if cycle:
        errors.append("dependency cycle: %s" % " -> ".join(cycle))
    return errors


# --------------------------------------------------------------------------
# Frontier
# --------------------------------------------------------------------------

def blocker_satisfied(graph, dep):
    if dep in questions_by_id(graph):
        return bool(questions_by_id(graph)[dep].get("answered"))
    task = tasks_by_id(graph).get(dep)
    return bool(task) and task.get("status") in SATISFYING


def ready_tasks(graph):
    ready = []
    for task in graph["tasks"]:
        if task.get("status") in ("blocked", "ready"):
            if all(blocker_satisfied(graph, d) for d in task.get("blocked_by") or []):
                ready.append(task["id"])
    return ready


def scopes_overlap(a, b):
    a, b = a.rstrip("/*"), b.rstrip("/*")
    if fnmatch.fnmatch(a, b) or fnmatch.fnmatch(b, a):
        return True
    return a == b or a.startswith(b + "/") or b.startswith(a + "/")


# --------------------------------------------------------------------------
# Verification evidence
# --------------------------------------------------------------------------

def covered_criteria(task, revision):
    covered = set()
    for ver in task.get("verifications") or []:
        if ver.get("result") == "pass" and ver.get("revision") == revision:
            covered.update(ver.get("criteria") or [])
    return covered


def verification_errors(task, revision, what):
    errors = []
    needed = set(task.get("acceptance_criteria") or [])
    if revision is None:
        return ["%s: no %s revision recorded" % (task["id"], what)]
    covered = covered_criteria(task, revision)
    missing = sorted(needed - covered)
    if missing:
        errors.append("%s: verification at %s revision %s does not cover "
                      "criteria %s (covered: %s)"
                      % (task["id"], what, revision, ", ".join(missing),
                         ", ".join(sorted(covered)) or "none"))
    stale = [v for v in task.get("verifications") or []
             if v.get("result") == "pass" and v.get("revision") != revision]
    if stale and not covered:
        errors.append("%s: passing verification exists only at old revision(s) %s, "
                      "not at %s" % (task["id"],
                                     ", ".join(sorted({v["revision"] for v in stale})),
                                     revision))
    return errors


# --------------------------------------------------------------------------
# Repair budget (bounded loop inside a task)
# --------------------------------------------------------------------------

def repeated_failure(task):
    attempts = (task.get("repair") or {}).get("attempts") or []
    if len(attempts) < 2:
        return False
    return (attempts[-1].get("failure_signature") ==
            attempts[-2].get("failure_signature"))


def _parse_iso(value):
    if not isinstance(value, str) or not value:
        return None
    try:
        parsed = datetime.datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError:
        return None
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=datetime.timezone.utc)
    return parsed


def repair_seconds(task):
    """Summed attempt durations; only attempts carrying both
    `started_at` and `ended_at` ISO timestamps contribute."""
    total = 0.0
    for att in (task.get("repair") or {}).get("attempts") or []:
        start, end = _parse_iso(att.get("started_at")), _parse_iso(att.get("ended_at"))
        if start is not None and end is not None:
            total += max(0.0, (end - start).total_seconds())
    return total


def repair_errors(task, new_status):
    """Guards for leaving `repairing` and for entering it."""
    errors = []
    repair = task.get("repair") or {}
    attempts = repair.get("attempts") or []
    max_attempts = repair.get("max_attempts")
    max_seconds = repair.get("max_seconds")
    seconds = repair_seconds(task)
    seconds_exhausted = (isinstance(max_seconds, (int, float))
                         and not isinstance(max_seconds, bool)
                         and seconds > max_seconds)
    if new_status == "repairing":
        if isinstance(max_attempts, int) and len(attempts) >= max_attempts:
            errors.append("%s: repair budget exhausted (%d/%d attempts); "
                          "new diagnosis required before more repair"
                          % (task["id"], len(attempts), max_attempts))
        if seconds_exhausted:
            errors.append("%s: repair budget exhausted (%.0f/%s seconds); "
                          "new diagnosis required before more repair"
                          % (task["id"], seconds, max_seconds))
    if new_status == "in_progress" and task.get("status") == "repairing":
        if seconds_exhausted:
            errors.append("%s: repair budget exhausted (%.0f/%s seconds); "
                          "transition to blocked instead: new diagnosis required"
                          % (task["id"], seconds, max_seconds))
        if isinstance(max_attempts, int) and len(attempts) >= max_attempts:
            errors.append("%s: repair budget exhausted (%d/%d attempts); "
                          "transition to blocked instead: new diagnosis required"
                          % (task["id"], len(attempts), max_attempts))
        if repeated_failure(task):
            last, prev = attempts[-1], attempts[-2]
            if not last.get("diagnosis") or last.get("diagnosis") == prev.get("diagnosis"):
                errors.append("%s: same failure repeated (%s) without progress; "
                              "new diagnosis required (record a different "
                              "repair.attempts diagnosis before retrying)"
                              % (task["id"], last.get("failure_signature")))
    return errors


# --------------------------------------------------------------------------
# Git (restart safety and merged-ness; delegated-autonomy SS3, merged-branch)
# --------------------------------------------------------------------------

def run_git(repo, *args):
    try:
        proc = subprocess.run(["git", "-C", repo] + list(args),
                              capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.SubprocessError):
        return None
    return proc.returncode, proc.stdout.strip()


def git_repo_for(plan_path, repo_arg):
    if repo_arg:
        return repo_arg
    base = os.path.dirname(os.path.abspath(plan_path)) or "."
    got = run_git(base, "rev-parse", "--show-toplevel")
    return got[1] if got and got[0] == 0 else None


def branch_head(repo, branch):
    if not repo or not branch:
        return None
    got = run_git(repo, "rev-parse", "--verify", branch)
    return got[1] if got and got[0] == 0 else None


def worktrees(repo):
    """Parse `git worktree list --porcelain` (never the human output)."""
    if not repo:
        return []
    got = run_git(repo, "worktree", "list", "--porcelain")
    if not got or got[0] != 0:
        return []
    out, current = [], {}
    for line in got[1].splitlines() + [""]:
        if not line:
            if current:
                out.append(current)
            current = {}
        elif line.startswith("worktree "):
            current["path"] = line[len("worktree "):]
        elif line.startswith("branch refs/heads/"):
            current["branch"] = line[len("branch refs/heads/"):]
    return out


def is_merged(task, repo, target="main"):
    """Merged-ness per delegated-autonomy/reference/merged-branch-check.md.

    Returns (merged, reason). The landed record is primary evidence; git
    signals are a fallback heuristic. A branch with zero own commits is
    never merged (it may be a fresh builder worktree).
    """
    branch = task.get("branch")
    if not repo or not branch:
        return False, "no git repo or no branch recorded"
    head = branch_head(repo, branch)
    if head is None:
        return False, "branch %s not found" % branch
    target_head = branch_head(repo, target)
    if target_head and head == target_head:
        return False, "branch has zero own commits; never treated as merged"
    landed = task.get("landed") or {}
    if landed.get("landing_sha"):
        if landed.get("tip_sha") and landed["tip_sha"] != head:
            return False, "branch tip moved after landing (%s != %s)" % (head, landed["tip_sha"])
        anc = run_git(repo, "merge-base", "--is-ancestor", landed["landing_sha"], target)
        if anc and anc[0] == 0:
            return True, "landed record: %s is in %s" % (landed["landing_sha"], target)
        return False, "landing commit %s is not an ancestor of %s" % (landed["landing_sha"], target)
    anc = run_git(repo, "merge-base", "--is-ancestor", branch, target)
    if anc and anc[0] == 0:
        return True, "git heuristic: branch is an ancestor of %s" % target
    cherry = run_git(repo, "cherry", target, branch)
    if cherry and cherry[0] == 0 and not any(
            line.startswith("+") for line in cherry[1].splitlines()):
        return True, "git heuristic: git cherry shows no unmerged commits"
    tree = run_git(repo, "merge-tree", "--write-tree", target, branch)
    main_tree = run_git(repo, "rev-parse", "%s^{tree}" % target)
    if tree and main_tree and tree[0] == 0 and tree[1].splitlines()[:1] == [main_tree[1]]:
        return True, "git heuristic: merge-tree equals %s tree" % target
    return False, "no landed record and no git heuristic proves it merged"


def restart_warnings(graph, repo):
    """Compare saved status with git/worktrees. Flags duplicate starts."""
    warnings = []
    by_branch, by_worktree = {}, {}
    for task in graph["tasks"]:
        if task.get("status") in ("ready", "in_progress", "review", "repairing"):
            if task.get("branch"):
                by_branch.setdefault(task["branch"], []).append(task["id"])
            if task.get("worktree"):
                by_worktree.setdefault(task["worktree"], []).append(task["id"])
    for branch, ids in by_branch.items():
        if len(ids) > 1:
            warnings.append("duplicate in-flight branch %s used by %s; "
                            "a restart must not start it twice" % (branch, ", ".join(ids)))
    for path, ids in by_worktree.items():
        if len(ids) > 1:
            warnings.append("duplicate worktree %s used by %s" % (path, ", ".join(ids)))
    wts = worktrees(repo)
    wt_by_branch = {w["branch"]: w["path"] for w in wts if w.get("branch")}
    for task in graph["tasks"]:
        tid, status, branch = task["id"], task.get("status"), task.get("branch")
        if status == "in_progress":
            if branch and repo and branch_head(repo, branch) is None:
                warnings.append("%s: in_progress but branch %s does not exist; "
                                "work may be lost or not started" % (tid, branch))
            if branch and repo and branch not in wt_by_branch:
                warnings.append("%s: in_progress but no worktree holds %s; "
                                "builder may have died (inspect before relaunching)" % (tid, branch))
            if task.get("worktree") and not os.path.isdir(task["worktree"]):
                warnings.append("%s: recorded worktree %s is missing" % (tid, task["worktree"]))
        if status in ("blocked", "ready") and branch and repo:
            head = branch_head(repo, branch)
            if head:
                got = run_git(repo, "rev-list", "--count", "HEAD..%s" % branch)
                ahead = got[1] if got and got[0] == 0 else "?"
                if task.get("tip_sha") and task["tip_sha"] != head:
                    warnings.append("%s: saved tip %s != branch head %s; "
                                    "branch moved since the plan was written" % (tid, task["tip_sha"], head))
                elif not task.get("tip_sha"):
                    warnings.append("%s: %s but branch %s already exists "
                                    "(%s commits ahead of HEAD); "
                                    "do not start a duplicate" % (tid, status, branch, ahead))
        if status in ("review", "in_progress", "repairing") and branch and task.get("tip_sha"):
            head = branch_head(repo, branch) if repo else None
            if head and head != task["tip_sha"]:
                warnings.append("%s: branch %s moved: saved tip %s, current head %s"
                                % (tid, branch, task["tip_sha"], head))
    return warnings


# --------------------------------------------------------------------------
# Transition guards (step 2: controlled status transitions)
# --------------------------------------------------------------------------

def delivery_branch(graph):
    return graph.get("delivery_branch") or "main"


def integration_branch(graph):
    return graph.get("integration_branch") or "main"


def warn_mentions_task(warn, tid):
    """Exact-id token match: T1 must not match T10."""
    return bool(re.search(r"(?<![A-Za-z0-9_-])%s(?![A-Za-z0-9_-])"
                          % re.escape(tid), warn))


def start_guard_errors(graph, task):
    """Guards shared by every transition into `in_progress`."""
    errors = []
    tid = task["id"]
    unmet = [d for d in task.get("blocked_by") or [] if not blocker_satisfied(graph, d)]
    if unmet:
        errors.append("%s: cannot start; blockers not satisfied: %s" % (tid, ", ".join(unmet)))
    for other in graph["tasks"]:
        if other["id"] != tid and other.get("status") == "in_progress":
            for a in task.get("scope") or []:
                for b in other.get("scope") or []:
                    if scopes_overlap(a, b):
                        errors.append("%s: scope %s overlaps in-progress %s scope %s; "
                                      "serialize or merge the tasks" % (tid, a, other["id"], b))
    if task.get("branch"):
        for other in graph["tasks"]:
            if other["id"] != tid and other.get("branch") == task["branch"] \
                    and other.get("status") in ("in_progress", "review", "repairing"):
                errors.append("%s: branch %s already in flight on %s; duplicate start refused"
                              % (tid, task["branch"], other["id"]))
    return errors


def transition_errors(graph, task, new_status, repo):
    errors = []
    tid, old = task["id"], task.get("status")
    if new_status not in STATUSES:
        return ["unknown status %r" % new_status]
    if new_status not in ALLOWED.get(old, set()):
        errors.append("%s: illegal transition %s -> %s (allowed: %s)"
                      % (tid, old, new_status,
                         ", ".join(sorted(ALLOWED.get(old, set()))) or "none"))
        return errors
    if new_status == "ready":
        unmet = [d for d in task.get("blocked_by") or [] if not blocker_satisfied(graph, d)]
        if unmet:
            errors.append("%s: cannot become ready; blockers not satisfied: %s"
                          % (tid, ", ".join(unmet)))
    if new_status == "in_progress":
        errors.extend(start_guard_errors(graph, task))
    if new_status == "review" and not task.get("tip_sha"):
        errors.append("%s: cannot enter review without a recorded tip_sha" % tid)
    if new_status == "integrated":
        review = task.get("review") or {}
        if review.get("verdict") != "pass":
            errors.append("%s: review -> integrated needs a passing review" % tid)
        head = branch_head(repo, task.get("branch")) or task.get("tip_sha")
        if review.get("sha") and head and review["sha"] != head:
            errors.append("%s: stale review: reviewed %s but branch head is %s; "
                          "review applies only to the current branch SHA"
                          % (tid, review["sha"], head))
        if review.get("sha"):
            errors.extend(verification_errors(task, review["sha"], "reviewed"))
        if repo and review.get("sha"):
            target = integration_branch(graph)
            anc = run_git(repo, "merge-base", "--is-ancestor", review["sha"], target)
            proved = bool(anc and anc[0] == 0)
            if not proved:
                landed = task.get("landed") or {}
                if landed.get("landing_sha"):
                    lanc = run_git(repo, "merge-base", "--is-ancestor",
                                   landed["landing_sha"], target)
                    proved = bool(lanc and lanc[0] == 0)
            if not proved:
                errors.append("%s: review -> integrated needs proof that reviewed "
                              "SHA %s is in integration branch %s "
                              "(merge-base --is-ancestor failed and no landed "
                              "record proves it); merge it first"
                              % (tid, review["sha"], target))
    if new_status == "verified":
        candidate = graph.get("candidate_sha")
        errors.extend(verification_errors(task, candidate, "candidate"))
    if new_status == "done":
        landed = task.get("landed") or {}
        if not landed.get("landing_sha"):
            errors.append("%s: verified -> done needs a landed record "
                          "(tip_sha and landing_sha)" % tid)
        elif repo:
            merged, reason = is_merged(task, repo, delivery_branch(graph))
            if not merged:
                errors.append("%s: not landed: %s" % (tid, reason))
    errors.extend(repair_errors(task, new_status))
    return errors


